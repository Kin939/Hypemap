class HR(Flowable):
    def __init__(self, width="100%", thickness=0.6, color=LINE, spaceAfter=8, spaceBefore=4):
        super().__init__()
        self.width = width
        self.thickness = thickness
        self.color = color
        self.spaceAfter = spaceAfter
        self.spaceBefore = spaceBefore

    def wrap(self, *a):
        return (170 * mm, self.spaceBefore + self.thickness + self.spaceAfter)

    def draw(self):
        self.canv.setStrokeColor(self.color)
        self.canv.setLineWidth(self.thickness)
        w = 170 * mm
        self.canv.line(0, self.spaceBefore + self.thickness / 2, w, self.spaceBefore + self.thickness / 2)


