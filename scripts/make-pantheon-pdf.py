def img_bytes(path: Path, max_px: int = 700) -> bytes:
    im = Image.open(path).convert("RGB")
    im.thumbnail((max_px, max_px), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, format="JPEG", quality=82)
    return buf.getvalue()


def rl_img(path: Path, w_mm: float, h_mm: float | None = None) -> RLImage:
    data = img_bytes(path, max_px=800)
    return RLImage(io.BytesIO(data), width=w_mm * mm, height=(h_mm or w_mm) * mm)


